"""Editable PowerPoint version of the weekly report (16:9, EN or AR/RTL), built only from facts.json.

The deck reads the finished facts dict (including `ai_summary`), so it never computes a number or calls an LLM:
every figure is formatted with the same helpers as the PDF. Text boxes and tables are native shapes so the
client can edit them; only the three 8-week charts are pictures (the same matplotlib PNGs as the PDF).

Arabic: every paragraph gets `a:pPr rtl="1"` and right alignment, table columns are physically mirrored (label
column on the right; `tblPr rtl` is avoided because LibreOffice ignores it and PowerPoint would double-mirror),
and runs use Arial for both Latin and complex script (it ships with Windows and macOS and has Arabic glyphs).
Digits stay Western, as in the PDF.
"""

import io
from pathlib import Path

from lxml import etree
from pptx import Presentation
from pptx.dml.color import RGBColor
from pptx.enum.shapes import MSO_SHAPE
from pptx.enum.text import MSO_ANCHOR, PP_ALIGN
from pptx.oxml.ns import qn
from pptx.util import Emu, Inches, Pt

from p3.report.charts import trend_chart_pngs
from p3.report.i18n import BRIDGE_LABELS_AR, ISSUE_LABELS, KPI_LABELS_AR, MAIN_KPIS, STRINGS
from p3.report.render import arrow, fmt_change, fmt_value, money, pct, signed, tone

# Same palette as report.html.j2 / charts.py
INK, MUTED, LINE, SOFT, ACCENT = "1F2933", "616E7C", "E4E7EB", "F5F7FA", "2F6F5E"
GOOD, BAD, WARN_BG, WARN, WARN_LINE, BANNER, BANNER_LINE, WHITE = (
    "1B7F4B", "B42318", "FFF7E6", "8A5A00", "F3D9A4", "FDECEA", "F5C2BD", "FFFFFF")
FONT = "Arial"
SLIDE_W, SLIDE_H = Emu(12_192_000), Emu(6_858_000)  # PowerPoint widescreen 16:9 (13.333 x 7.5 in)
MARGIN = Inches(0.6)
CONTENT_W = SLIDE_W - 2 * MARGIN
TONE_COLOR = {"good": GOOD, "bad": BAD, "flat": MUTED}
LRE, PDF = "\u202a", "\u202c"  # left-to-right embedding: keeps "-7,562.57 (-20.0%)" and dates in order inside RTL

DECK_STRINGS = {
    "en": {"footer": "Synthetic data — generated by a seeded script, not a real store",
           "missing_dq": "Missing cost and data quality",
           "no_issues": "No data-quality issues this week.",
           "issue": "Issue", "count": "Count", "amount": "Amount (SAR)"},
    "ar": {"footer": "Synthetic data — بيانات اصطناعية مولّدة ببرنامج، ليست لمتجر حقيقي",
           "missing_dq": "التكلفة المفقودة وجودة البيانات",
           "no_issues": "لا توجد مشكلات في جودة البيانات هذا الأسبوع.",
           "issue": "المشكلة", "count": "العدد", "amount": "المبلغ (ريال)"},
}


def deck_titles(lang: str) -> list[str]:
    """The seven slide titles, in order (also used by the tests)."""
    t, d = STRINGS[lang], DECK_STRINGS[lang]
    return [t["title"], t["kpis"], t["summary"], t["bridge"], t["trends"], t["movers"], d["missing_dq"]]


class _Deck:
    def __init__(self, facts: dict, lang: str) -> None:
        self.f, self.lang, self.rtl = facts, lang, lang == "ar"
        self.t, self.d = STRINGS[lang], DECK_STRINGS[lang]
        self.prs = Presentation()
        self.prs.slide_width, self.prs.slide_height = SLIDE_W, SLIDE_H
        self.prs.core_properties.title = f"{self.t['title']} {facts['week']['iso_week']} (synthetic data)"
        self.prs.core_properties.subject = facts["notice"]
        self.prs.core_properties.author = "P3 profit reporting (synthetic data)"

    def n(self, s: str) -> str:
        """Numbers, dates, ISO weeks and signed changes read left-to-right even inside an Arabic paragraph."""
        return f"{LRE}{s}{PDF}" if self.rtl else s

    # ---- text primitives -------------------------------------------------------------------------------------
    def _style_paragraph(self, p, align: str | None = None) -> None:
        pPr = p._p.get_or_add_pPr()
        if self.rtl:
            pPr.set("rtl", "1")
        p.alignment = {"start": PP_ALIGN.RIGHT if self.rtl else PP_ALIGN.LEFT,
                       "end": PP_ALIGN.LEFT if self.rtl else PP_ALIGN.RIGHT,
                       "center": PP_ALIGN.CENTER}[align or "start"]

    def _run(self, p, text: str, size: float, color: str = INK, bold: bool = False) -> None:
        r = p.add_run()
        r.text = text
        r.font.size, r.font.bold, r.font.name = Pt(size), bold, FONT
        r.font.color.rgb = RGBColor.from_string(color)
        rPr = r._r.get_or_add_rPr()
        rPr.set("lang", "ar-SA" if self.rtl else "en-US")
        # East-Asian and complex-script faces too, so Arabic never falls back to a Latin-only font.
        # Schema order inside a:rPr is latin, ea, cs.
        ea, cs = etree.Element(qn("a:ea"), typeface=FONT), etree.Element(qn("a:cs"), typeface=FONT)
        latin = rPr.find(qn("a:latin"))
        latin.addnext(ea)
        ea.addnext(cs)

    def _fill_frame(self, tf, paragraphs: list, size: float, color: str = INK, bold: bool = False,
                    align: str | None = None, bullets: bool = False, space_after: float = 0) -> None:
        """paragraphs: list of str or list of (text, color, bold) run tuples."""
        tf.word_wrap = True
        for i, para in enumerate(paragraphs):
            p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
            self._style_paragraph(p, align)
            if space_after:
                p.space_after = Pt(space_after)
            if bullets:
                pPr = p._p.get_or_add_pPr()
                pPr.set("marL", str(Emu(Inches(0.3))))
                pPr.set("indent", str(-Emu(Inches(0.3))))
                bu = etree.SubElement(pPr, qn("a:buChar"))
                bu.set("char", "•")
            runs = [(para, color, bold)] if isinstance(para, str) else para
            for text, c, b in runs:
                self._run(p, text, size, c or color, b)

    def text(self, slide, x, y, w, h, paragraphs: list, size: float = 14, color: str = INK, bold: bool = False,
             align: str | None = None, bullets: bool = False, space_after: float = 0, anchor=MSO_ANCHOR.TOP):
        box = slide.shapes.add_textbox(self.x(x, w), y, w, h)
        tf = box.text_frame
        tf.vertical_anchor = anchor
        tf.margin_left = tf.margin_right = Inches(0.05)
        self._fill_frame(tf, paragraphs, size, color, bold, align, bullets, space_after)
        return box

    def box(self, slide, x, y, w, h, fill: str, line: str | None = None, rounded: bool = True):
        shape = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE if rounded else MSO_SHAPE.RECTANGLE,
                                       self.x(x, w), y, w, h)
        if rounded:
            shape.adjustments[0] = 0.06
        shape.fill.solid()
        shape.fill.fore_color.rgb = RGBColor.from_string(fill)
        if line:
            shape.line.color.rgb = RGBColor.from_string(line)
            shape.line.width = Pt(0.75)
        else:
            shape.line.fill.background()
        shape.shadow.inherit = False
        tf = shape.text_frame
        tf.margin_left = tf.margin_right = Inches(0.18)
        tf.margin_top = tf.margin_bottom = Inches(0.1)
        return shape

    def x(self, x, w):
        """Mirror a left offset for RTL so layouts read right-to-left."""
        return SLIDE_W - x - w if self.rtl else x

    def table(self, slide, x, y, w, header: list[str], rows: list[list], widths: list[float],
              aligns: list[str], row_h=Inches(0.32), size: float = 11, total_rows: set[int] | None = None,
              cell_colors: dict[tuple[int, int], str] | None = None):
        """rows: list of cell texts; widths are fractions. Columns are mirrored for RTL."""
        order = list(range(len(header)))[::-1] if self.rtl else list(range(len(header)))
        shape = slide.shapes.add_table(len(rows) + 1, len(header), self.x(x, w), y, w, row_h * (len(rows) + 1))
        tbl = shape.table
        tbl.first_row, tbl.horz_banding = True, False
        for j, src in enumerate(order):
            tbl.columns[j].width = int(w * widths[src])
        total_rows = total_rows or set()
        cell_colors = cell_colors or {}
        for i, row in enumerate([header] + rows):
            tbl.rows[i].height = row_h
            for j, src in enumerate(order):
                cell = tbl.cell(i, j)
                cell.fill.solid()
                is_total = i - 1 in total_rows
                cell.fill.fore_color.rgb = RGBColor.from_string(SOFT if i == 0 or is_total else WHITE)
                cell.margin_left = cell.margin_right = Inches(0.08)
                cell.margin_top = cell.margin_bottom = Inches(0.03)
                cell.vertical_anchor = MSO_ANCHOR.MIDDLE
                color = MUTED if i == 0 else cell_colors.get((i - 1, src), INK)
                text = str(row[src])
                if i > 0 and aligns[src] == "end" and any(c.isdigit() for c in text):
                    text = self.n(text)
                self._fill_frame(cell.text_frame, [text], size - (1 if i == 0 else 0), color,
                                 bold=(i == 0 or is_total), align=aligns[src])
        return shape

    # ---- slide scaffolding -----------------------------------------------------------------------------------
    def slide(self, title: str):
        s = self.prs.slides.add_slide(self.prs.slide_layouts[6])
        self.text(s, MARGIN, Inches(0.35), CONTENT_W, Inches(0.7), [title], size=26, bold=True)
        bar = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, self.x(MARGIN, Inches(1.2)), Inches(1.02), Inches(1.2), Pt(3))
        bar.fill.solid()
        bar.fill.fore_color.rgb = RGBColor.from_string(ACCENT)
        bar.line.fill.background()
        self.footer(s)
        return s

    def footer(self, s) -> None:
        y = SLIDE_H - Inches(0.45)
        line = s.shapes.add_connector(1, MARGIN, y, SLIDE_W - MARGIN, y)
        line.line.color.rgb = RGBColor.from_string(LINE)
        line.line.width = Pt(0.75)
        wk = self.f["week"]
        self.text(s, MARGIN, y + Inches(0.03), Inches(7.5), Inches(0.35), [self.d["footer"]], size=10, color=BAD,
                  bold=True)
        self.text(s, SLIDE_W - MARGIN - Inches(4.5), y + Inches(0.03), Inches(4.5), Inches(0.35),
                  [f"{self.t['title']} · {self.n(wk['iso_week'])}"], size=10, color=MUTED, align="end")

    # ---- slides ----------------------------------------------------------------------------------------------
    def title_slide(self) -> None:
        s = self.prs.slides.add_slide(self.prs.slide_layouts[6])
        wk = self.f["week"]
        band = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, SLIDE_W, Inches(0.25))
        band.fill.solid()
        band.fill.fore_color.rgb = RGBColor.from_string(ACCENT)
        band.line.fill.background()
        self.text(s, MARGIN, Inches(1.5), CONTENT_W, Inches(1.0), [self.t["title"]], size=44, bold=True)
        self.text(s, MARGIN, Inches(2.5), CONTENT_W, Inches(0.5), [self.t["store"]], size=20, color=MUTED)
        self.text(s, MARGIN, Inches(3.2), CONTENT_W, Inches(0.6),
                  [[(f"{self.t['week']} {self.n(wk['iso_week'])}", ACCENT, True),
                    (f"  ·  {self.n(wk['start'] + ' – ' + wk['end'])}", INK, False)]],
                  size=22)
        banner = self.box(s, MARGIN, Inches(4.4), CONTENT_W, Inches(1.1), BANNER, BANNER_LINE)
        banner.text_frame.vertical_anchor = MSO_ANCHOR.MIDDLE
        self._fill_frame(banner.text_frame, [self.t["banner"]], 16, BAD, bold=True)
        self.footer(s)

    def kpi_slide(self) -> None:
        s = self.slide(self.t["kpis"])
        self.text(s, MARGIN, Inches(1.15), CONTENT_W, Inches(0.4), [self.t["vs_prev"]], size=13, color=MUTED)
        gap = Inches(0.3)
        cw, ch = int((CONTENT_W - 2 * gap) / 3), Inches(2.2)
        for n, key in enumerate(MAIN_KPIS):
            k = self.f["kpis"][key]
            col, row = n % 3, n // 3
            x, y = MARGIN + col * (cw + gap), Inches(1.75) + row * (ch + gap)
            card = self.box(s, x, y, cw, ch, SOFT, LINE)
            label = KPI_LABELS_AR.get(key, k["label"]) if self.rtl else k["label"]
            self._fill_frame(card.text_frame, [
                [(label, MUTED, False)],
                [(self.n(fmt_value(k["this_week"], k["unit"])), INK, True)],
                [(self.n(f"{arrow(k['change']['direction'])} {fmt_change(k)}"), TONE_COLOR[tone(k)], True)],
            ], 14)
            paras = card.text_frame.paragraphs
            for p, size in zip(paras, (14, 30, 15), strict=True):
                p.space_after = Pt(6)
                for r in p.runs:
                    r.font.size = Pt(size)

    def summary_slide(self) -> None:
        s = self.slide(self.t["summary"])
        ai = self.f.get("ai_summary") or {}
        y = Inches(1.3)
        if ai.get("notice"):
            warn = self.box(s, MARGIN, y, CONTENT_W, Inches(0.5), WARN_BG, WARN_LINE)
            warn.text_frame.vertical_anchor = MSO_ANCHOR.MIDDLE
            self._fill_frame(warn.text_frame, [ai["notice"]], 13, WARN, bold=True)
            y += Inches(0.65)
        self.text(s, MARGIN, y, CONTENT_W, Inches(4.6), list(ai.get("bullets") or []), size=17, bullets=True,
                  space_after=10)
        if ai.get("source") == "llm":
            label = f"{self.t['summary_ai']} · {ai.get('provider')} {ai.get('model')}"
        else:
            label = self.t["summary_template"] + (f" · {ai['reason']}" if ai.get("reason") else "")
        self.text(s, MARGIN, Inches(6.45), CONTENT_W, Inches(0.4), [label], size=11, color=MUTED)

    def _bridge_rows(self, block: str, with_op: bool = True) -> tuple[list[list], set[int]]:
        label = (lambda lb: BRIDGE_LABELS_AR.get(lb, lb)) if self.rtl else (lambda lb: lb)
        rows, totals = [], set()
        for i, r in enumerate(self.f["bridge"][block]):
            cells = [label(r["label"]), money(r["this_week"]), money(r["previous_week"])]
            rows.append([r["op"] or ""] + cells if with_op else cells)
            if r["op"] == "=":
                totals.add(i)
        return rows, totals

    def bridge_slide(self) -> None:
        s = self.slide(self.t["bridge"])
        half = int((CONTENT_W - Inches(0.4)) / 2)
        head = ["", "", self.t["this_week"], self.t["previous_week"]]
        widths, aligns = [0.06, 0.52, 0.21, 0.21], ["center", "start", "end", "end"]
        right = MARGIN + half + Inches(0.4)
        for x, block, title in ((MARGIN, "revenue", self.t["bridge_revenue"]),
                                (right, "profit", self.t["bridge_profit"])):
            self.text(s, x, Inches(1.2), half, Inches(0.4), [title], size=14, bold=True, color=ACCENT)
            rows, totals = self._bridge_rows(block)
            self.table(s, x, Inches(1.6), half, head, rows, widths, aligns, total_rows=totals)
        y = Inches(1.6) + Inches(0.32) * (len(self.f["bridge"]["revenue"]) + 1) + Inches(0.2)
        self.text(s, MARGIN, y, half, Inches(0.4), [self.t["bridge_excluded"]], size=14, bold=True, color=ACCENT)
        rows, _ = self._bridge_rows("excluded", with_op=False)
        self.table(s, MARGIN, y + Inches(0.4), half, [""] + head[2:], rows, [0.58, 0.21, 0.21],
                   ["start", "end", "end"], row_h=Inches(0.28), size=10)
        note = self.t["margin_note"].format(margin=self.f["kpis"]["net_margin_pct_known_cost"]["this_week"],
                                            excluded=money(self.f["missing_cost"]["net_revenue_this_week"]))
        y2 = Inches(1.6) + Inches(0.32) * (len(self.f["bridge"]["profit"]) + 1) + Inches(0.2)
        self.text(s, right, y2, half, Inches(0.8), [note], size=11, color=MUTED)

    def trend_slide(self) -> None:
        s = self.slide(self.t["trends"])
        pngs = trend_chart_pngs(self.f["trend"])
        gap = Inches(0.3)
        w = int((CONTENT_W - 2 * gap) / 3)
        for n, (key, caption) in enumerate((("net_revenue", self.t["trend_revenue"]),
                                            ("net_profit", self.t["trend_profit"]),
                                            ("margin", self.t["trend_margin"]))):
            x = MARGIN + n * (w + gap)
            frame = self.box(s, x, Inches(1.5), w, Inches(3.0), WHITE, LINE)
            self.text(s, x + Inches(0.15), Inches(1.65), w - Inches(0.3), Inches(0.5), [caption], size=15,
                      bold=True)
            pic = s.shapes.add_picture(io.BytesIO(pngs[key]), self.x(x + Inches(0.15), w - Inches(0.3)),
                                       Inches(2.3), width=w - Inches(0.3))
            pic.name = f"chart {key}"
            frame.height = pic.top + pic.height + Inches(0.2) - frame.top

    def movers_slide(self) -> None:
        s = self.slide(self.t["movers"])
        t, mv = self.t, self.f["movers"]
        head = ["", t["product"], t["profit_now"], t["profit_avg"], t["profit_change"], t["revenue_change"]]
        rows, colors = [], {}
        for group, items in ((t["risers"], mv["risers"]), (t["fallers"], mv["fallers"])):
            for i, m in enumerate(items):
                c = GOOD if m["profit_change"]["direction"] == "up" else BAD
                r = len(rows)
                colors[(r, 0)] = colors[(r, 4)] = c
                rows.append([group if i == 0 else "", f"{m['sku']} {m['product']}",
                             money(m["net_profit_this_week"]) if m["sold_this_week"] else t["no_sales"],
                             money(m["net_profit_prev4_avg"]),
                             f"{signed(m['profit_change']['abs'])} ({pct(m['profit_change']['pct'])})",
                             f"{signed(m['revenue_change']['abs'])} ({pct(m['revenue_change']['pct'])})"])
        self.table(s, MARGIN, Inches(1.4), CONTENT_W, head, rows, [0.07, 0.33, 0.13, 0.12, 0.17, 0.18],
                   ["start", "start", "end", "end", "end", "end"], row_h=Inches(0.48), size=13, cell_colors=colors)
        if mv.get("missing_cost_products"):
            items = "; ".join(self.n(f"{m['sku']} {signed(m['revenue_change']['abs'])} ({pct(m['revenue_change']['pct'])})")
                              for m in mv["missing_cost_products"])
            y = Inches(1.4) + Inches(0.48) * (len(rows) + 1) + Inches(0.25)
            self.text(s, MARGIN, y, CONTENT_W, Inches(0.6), [f"{t['missing_movers']}: {items}"], size=12,
                      color=MUTED)

    def missing_dq_slide(self) -> None:
        s = self.slide(self.d["missing_dq"])
        t, mc, dq = self.t, self.f["missing_cost"], self.f["data_quality"]
        half = int((CONTENT_W - Inches(0.4)) / 2)
        warn = self.box(s, MARGIN, Inches(1.4), half, Inches(3.6), WARN_BG, WARN_LINE)
        paras = [[(t["missing"], WARN, True)],
                 [(t["missing_text"].format(lines=mc["lines_this_week"], revenue=self.n(money(mc["net_revenue_this_week"]))),
                   INK, False)]]
        paras += [[(self.n(x['sku']) + " ", INK, True),
                   (f"{x['product']} — {x['lines_to_date']} {t['lines_to_date']}, {t['since']} {self.n(x['first_sale'])}",
                    INK, False)] for x in mc["skus"]]
        warn.text_frame.vertical_anchor = MSO_ANCHOR.TOP
        self._fill_frame(warn.text_frame, paras, 14, space_after=8)
        warn.text_frame.paragraphs[0].runs[0].font.size = Pt(18)
        for p in warn.text_frame.paragraphs[2:]:
            pPr = p._p.get_or_add_pPr()
            pPr.set("marL", str(Emu(Inches(0.3))))
            pPr.set("indent", str(-Emu(Inches(0.3))))
            etree.SubElement(pPr, qn("a:buChar")).set("char", "•")

        right = MARGIN + half + Inches(0.4)
        self.text(s, right, Inches(1.4), half, Inches(0.45), [t["dq"]], size=18, bold=True, color=ACCENT)
        y = Inches(1.95)
        issues = dq["issues_this_week"]
        if issues:
            rows = [[ISSUE_LABELS[self.lang].get(i["issue_type"], i["issue_type"]), str(i["count"]), money(i["amount"])]
                    for i in issues]
            self.table(s, right, y, half, [self.d["issue"], self.d["count"], self.d["amount"]], rows,
                       [0.56, 0.18, 0.26], ["start", "end", "end"], row_h=Inches(0.4), size=13)
            y += Inches(0.4) * (len(rows) + 1) + Inches(0.2)
        else:
            self.text(s, right, y, half, Inches(0.4), [self.d["no_issues"]], size=14)
            y += Inches(0.5)
        self.text(s, right, y, half, Inches(0.4), [t["dq_rejects"].format(n=dq["etl_rejects_all_time"])], size=13,
                  color=MUTED)

    def build(self) -> Presentation:
        self.title_slide()
        self.kpi_slide()
        self.summary_slide()
        self.bridge_slide()
        self.trend_slide()
        self.movers_slide()
        self.missing_dq_slide()
        if self.rtl:  # decorative shapes (bands, cards) carry an empty paragraph too: mark it RTL as well
            for slide in self.prs.slides:
                for p in slide._element.iter(qn("a:p")):
                    pPr = p.find(qn("a:pPr"))
                    if pPr is None:
                        pPr = etree.Element(qn("a:pPr"))
                        p.insert(0, pPr)
                    pPr.set("rtl", "1")
                    pPr.set("algn", pPr.get("algn", "r"))
        return self.prs


def build_deck(facts: dict, lang: str = "en") -> Presentation:
    if lang not in STRINGS:
        raise ValueError(f"unsupported language {lang!r}; expected en or ar")
    return _Deck(facts, lang).build()


def write_deck(facts: dict, out_path: Path, lang: str = "en") -> Path:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    build_deck(facts, lang).save(str(out_path))
    return out_path
